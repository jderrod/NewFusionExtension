"""Regenerate the test catalogue in docs/TESTING.md from the tests themselves.

    py -3 scripts/gen_test_catalogue.py            # rewrite the catalogue block
    py -3 scripts/gen_test_catalogue.py --check    # exit 1 if it is out of date

Every test is listed with its docstring (or its name when it has none), so the
documentation follows the code.  tests/test_docs.py fails when the block is
stale, which makes "update the docs with every change" part of the test run.
"""

import argparse
import ast
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TESTS = os.path.join(ROOT, "tests")
DOC = os.path.join(ROOT, "docs", "TESTING.md")
BEGIN = "<!-- BEGIN TEST CATALOGUE (generated by scripts/gen_test_catalogue.py; do not edit by hand) -->"
END = "<!-- END TEST CATALOGUE -->"


def _clean(text):
    text = " ".join(line.strip() for line in (text or "").strip().splitlines())
    return text.replace("|", "\\|")


def _humanize(name):
    return name[len("test_"):].replace("_", " ").capitalize() + "."


def collect():
    """[(module, module_doc, [(class, class_doc, [(test, description)])])] in file order."""
    out = []
    for fname in sorted(os.listdir(TESTS)):
        if not (fname.startswith("test_") and fname.endswith(".py")):
            continue
        with open(os.path.join(TESTS, fname), encoding="utf-8") as fh:
            tree = ast.parse(fh.read())
        classes = []
        for node in tree.body:
            if not isinstance(node, ast.ClassDef):
                continue
            tests = [(f.name, _clean(ast.get_docstring(f)) or _humanize(f.name))
                     for f in node.body
                     if isinstance(f, ast.FunctionDef) and f.name.startswith("test")]
            if tests:
                classes.append((node.name, _clean(ast.get_docstring(node)), tests))
        if classes:
            doc = ast.get_docstring(tree) or ""
            out.append((fname[:-3], _clean(doc.strip().split("\n\n")[0]), classes))
    return out


def render(catalogue):
    total = sum(len(t) for _, _, cls in catalogue for _, _, t in cls)
    lines = [BEGIN, "",
             "**%d tests** in %d modules. Run them all with `run_tests.bat` or"
             % (total, len(catalogue)),
             "`cd tests && py -3 -m unittest discover -p \"test_*.py\"`.", "",
             "| Module | Classes (tests) | Tests |", "|---|---|---|"]
    for mod, _, cls in catalogue:
        lines.append("| `%s.py` | %s | %d |" % (
            mod, ", ".join("`%s` (%d)" % (c, len(t)) for c, _, t in cls),
            sum(len(t) for _, _, t in cls)))
    lines.append("| **Total** | | **%d** |" % total)
    for mod, mdoc, cls in catalogue:
        lines += ["", "### `tests/%s.py`" % mod]
        if mdoc:
            lines += ["", mdoc]
        for cname, cdoc, tests in cls:
            lines += ["", "#### `%s`" % cname]
            if cdoc:
                lines += ["", cdoc]
            lines += ["", "| Test | What it verifies |", "|---|---|"]
            lines += ["| `%s` | %s |" % (t, d) for t, d in tests]
    lines += ["", END]
    return "\n".join(lines)


def current_block(text):
    m = re.search(re.escape(BEGIN) + r".*?" + re.escape(END), text, re.S)
    return m.group(0) if m else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    with open(DOC, encoding="utf-8") as fh:
        text = fh.read()
    block = render(collect())
    old = current_block(text)
    if a.check:
        ok = old == block
        print("test catalogue is %s" % ("up to date" if ok else "OUT OF DATE"))
        return 0 if ok else 1
    if old is None:
        raise SystemExit("markers not found in docs/TESTING.md")
    with open(DOC, "w", encoding="utf-8") as fh:
        fh.write(text.replace(old, block))
    print("docs/TESTING.md catalogue regenerated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
